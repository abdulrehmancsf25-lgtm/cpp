#include<iostream>
#define pi 3.14
using namespace std ;
int main(){
    int r = 5  ;
    cout << "Area of circle is " << 3.14 * r * r << endl ;
    cout << "Circumference is " << 3.14 * r * r << endl ;

    cout << "Area of circle is " << pi * r * r << endl ;
    cout << "Circumference is " << pi * r * r << endl ;
    return 0 ;
}